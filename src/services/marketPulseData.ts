export function getLiveMarketPulse(liveVix: number = 15.65): MarketPulseData {
  let regime: MarketPulseData['regime'] = 'CALM_TRENDING';
  let regimeTitle = 'Low Volatility Bullish Trend';
  let regimeDescription =
    'India VIX is well below 16.0, confirming an institutional trending regime. Stop losses hold reliably and directional swing strategies exhibit superior win rates.';

  if (liveVix > 21.0) {
    regime = 'HIGH_FEAR_BREAKDOWN';
    regimeTitle = 'High Volatility Crisis Breakdown';
    regimeDescription =
      'Elevated VIX above 21.0 indicates intense institutional hedging. Reduce position sizing to 0.5% RPT and require strict multi-timeframe confirmations.';
  } else if (liveVix > 17.5) {
    regime = 'VOLATILE_CHOP';
    regimeTitle = 'Elevated Volatility & Sideways Chop';
    regimeDescription =
      'VIX between 17.5 and 21.0 brings intraday whipsaws. Breakout false-positive rates increase. Tighten lookback stop losses and lock 1:1.5 partial profits.';
  }

  return {
    indiaVix: liveVix,
    indiaVixChangePct: 0.97,
    niftyAdvanceCount: 34,
    niftyDeclineCount: 16,
    marketBreadthPct: 72.0, // 72% of Nifty 50 above 50-day EMA
    fiiNetFlowCr: 1845.2, // +₹1,845 Cr Net Foreign Inflow
    diiNetFlowCr: 982.5, // +₹982 Cr Net Domestic Inflow
    regime,
    regimeTitle,
    regimeDescription,
    recommendedStrategies: [
      {
        name: 'Parabolic SAR + SMA 100 Swing',
        fitLevel: liveVix <= 17.5 ? 'OPTIMAL' : 'MODERATE',
        reason: 'Clean directional momentum with minimal fake whipsaws in low-VIX environments.',
      },
      {
        name: 'Opening Range Breakout (5M ORB)',
        fitLevel: liveVix > 16.0 && liveVix <= 21.0 ? 'OPTIMAL' : 'MODERATE',
        reason: 'Captures early-session volatility expansion at opening bell (09:15 - 09:20 AM).',
      },
      {
        name: 'Stochastic Oscillator Inflection',
        fitLevel: liveVix > 17.5 ? 'OPTIMAL' : 'CAUTION',
        reason: 'Mean-reversion performs best during range-bound chop; use caution during strong one-way trends.',
      },
    ],
  };
}

